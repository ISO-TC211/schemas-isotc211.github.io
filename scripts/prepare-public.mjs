#!/usr/bin/env node
// Replaces _plugins/build_source_generator.rb: stage the lutaml SPA output and
// the schema data files at their canonical top-level URLs (schemas/ prefix
// stripped) for Astro's public/ directory.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { join, relative } from 'node:path'

const DATA_EXTENSIONS = new Set([
  '.xsd', '.xml', '.xsl', '.xslt', '.sch', '.json', '.zip',
  '.gml', '.svg', '.png', '.txt', '.adoc', '.ent', '.dtd',
])
const SKIP_DIRS = new Set(['.git', 'vendor', '_site', 'node_modules', 'tools', '.archive'])

const root = process.cwd()
const pub = join(root, 'public')
rmSync(pub, { recursive: true, force: true })
mkdirSync(pub, { recursive: true })

let spaCount = 0
const spaBase = join(root, 'site')
if (existsSync(spaBase)) {
  cpSync(spaBase, pub, { recursive: true })
  const count = (dir) => readdirSync(dir, { withFileTypes: true }).reduce(
    (n, e) => (e.isDirectory() ? n + count(join(dir, e.name)) : n + 1), 0)
  spaCount = count(spaBase)
  console.log(`prepare-public: staged ${spaCount} SPA files from site/`)
} else {
  console.error('prepare-public: site/ missing — run make lxr-spas first')
  process.exit(1)
}

// site assets (favicons, logos) from the repo assets/ dir
const assetsBase = join(root, 'assets')
if (existsSync(assetsBase)) cpSync(assetsBase, join(pub, 'assets'), { recursive: true })

const vendorBase = join(root, 'vendor_schemas')
if (existsSync(vendorBase)) {
  cpSync(vendorBase, join(pub, 'vendor_schemas'), { recursive: true })
  console.log('prepare-public: staged vendor_schemas (legacy helper schemas)')
}

const schemasBase = join(root, 'schemas')
if (!existsSync(schemasBase)) {
  console.error('prepare-public: schemas/ missing — run make update first')
  process.exit(1)
}
const schemasReal = schemasBase // walk directly

let dataCount = 0
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue
      walk(join(dir, entry.name))
    } else if (DATA_EXTENSIONS.has(join(entry.name, '').slice(0, 0) + entry.name.slice(entry.name.lastIndexOf('.')))) {
      const rel = relative(schemasReal, join(dir, entry.name))
      const dest = join(pub, rel)
      mkdirSync(dest.slice(0, dest.lastIndexOf('/')), { recursive: true })
      cpSync(join(dir, entry.name), dest)
      dataCount++
    }
  }
}
walk(schemasReal)
console.log(`prepare-public: staged ${dataCount} schema data files at top-level URLs`)

// client-fetched indexes at site root + build-time data for routes
mkdirSync(join(root, 'src', 'data'), { recursive: true })
for (const f of ['schemas_index.json', 'resources_index.json']) {
  const src = join(root, f)
  if (existsSync(src)) {
    cpSync(src, join(pub, f))
    cpSync(src, join(root, 'src', 'data', f.replace('_', '-')))
  }
}

// codelist index generated by scripts/export-codelists.rb
const cl = join(root, 'codelists_index.json')
if (existsSync(cl)) {
  cpSync(cl, join(pub, 'codelists_index.json'))
  cpSync(cl, join(root, 'src', 'data', 'codelists-index.json'))
}
console.log('prepare-public: done')
